#!/usr/bin/env python3
"""
Synthesize the magnitude experiment into a results .md + traceable LaTeX macros.

Reads:
  results/magnitude/search_summary.csv        (variant -> mean_abs_within_r, dirmatch, ...)
  results/magnitude/ratings_GPT_4_1.csv        (reliability re-rating: rel_Y per state at temp 0.8)
Writes:
  results/magnitude/MAGNITUDE_RESULTS.md       (human-readable table + interpretation skeleton)
  results/magnitude/values_magnitude.tex       (\\baselineWithinR, \\bestWithinR, \\bestVariant, \\relYMean ...)
No prose claims are invented; only measured numbers are emitted.
"""
import csv, math, statistics as st
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
M = REPO / "results/magnitude"
STATES = ["work_engagement", "psych_safety", "work_creativity", "team_trust"]


def icc1(groups):
    groups = [g for g in groups if len(g) >= 2]
    if len(groups) < 2:
        return None
    k = st.mean(len(g) for g in groups)
    grand = st.mean(x for g in groups for x in g)
    n = len(groups)
    msb = sum(len(g) * (st.mean(g) - grand) ** 2 for g in groups) / (n - 1)
    msw = sum((x - st.mean(g)) ** 2 for g in groups for x in g) / sum(len(g) - 1 for g in groups)
    den = msb + (k - 1) * msw
    return (msb - msw) / den if den > 0 else None


def reliability():
    f = M / "ratings_GPT_4_1.csv"
    if not f.exists():
        return {}
    rows = [r for r in csv.DictReader(open(f)) if str(r.get("temperature")) == "0.8"]
    out = {}
    for s in STATES:
        g = defaultdict(list)
        for r in rows:
            v = r.get(s, "")
            if v not in ("", None):
                g[(r["employee_id"], r["day_index"])].append(float(v))
        out[s] = icc1(list(g.values()))
    return out


def fnum(x):
    try: return float(x)
    except (TypeError, ValueError): return None


def main():
    summ = {}
    sp = M / "search_summary.csv"
    if sp.exists():
        for r in csv.DictReader(open(sp)):
            summ[r["variant"]] = r
    rel = reliability()
    rel_vals = [v for v in rel.values() if v]
    rel_mean = st.mean(rel_vals) if rel_vals else None

    base = fnum(summ.get("V0_baseline", {}).get("mean_abs_within_r"))
    # best non-baseline by mean_abs_within_r among direction-preserving variants
    cand = {k: v for k, v in summ.items()
            if k != "V0_baseline" and fnum(v.get("dirmatch_within_pct")) and fnum(v["dirmatch_within_pct"]) >= 55}
    best_k = max(cand, key=lambda k: fnum(cand[k]["mean_abs_within_r"]), default=None)
    best = fnum(cand[best_k]["mean_abs_within_r"]) if best_k else None

    # results md
    with open(M / "MAGNITUDE_RESULTS.md", "w") as f:
        f.write("# Magnitude experiment — results\n\n")
        f.write(f"Single-rating reliability rel_Y (gpt-4.1, temp 0.8): "
                + ", ".join(f"{s}={_r(rel.get(s))}" for s in STATES)
                + f" (mean {_r(rel_mean)}). High reliability => attenuation is NOT measurement noise.\n\n")
        f.write("## Prompt-intervention search (mean |within_r| vs human meta 0.20–0.70)\n\n")
        f.write("| variant | mean\\|within_r\\| | high-conf | dir-match % | rho vs meta | n_pairs |\n")
        f.write("|---|---|---|---|---|---|\n")
        for k, v in summ.items():
            f.write(f"| {k} | {_r(fnum(v.get('mean_abs_within_r')))} | "
                    f"{_r(fnum(v.get('mean_abs_within_r_highconf')))} | "
                    f"{_r(fnum(v.get('dirmatch_within_pct')))} | "
                    f"{_r(fnum(v.get('rho_within_vs_meta')))} | {v.get('n_pairs','')} |\n")
        if base and best:
            f.write(f"\n**Baseline** {_r(base)} -> **best ({best_k})** {_r(best)} "
                    f"({(best/base-1)*100:+.0f}%). Human meta band 0.20–0.70.\n")
        f.write("\n(Interpretation paragraph for the manuscript is written by hand from these numbers.)\n")

    # macros
    with open(M / "values_magnitude.tex", "w") as f:
        f.write("% auto-generated by synthesize_magnitude.py — magnitude experiment numbers\n")
        if rel_mean is not None:
            f.write(f"\\newcommand{{\\relYMean}}{{{rel_mean:.2f}}}\n")
        if base is not None:
            f.write(f"\\newcommand{{\\baselineWithinR}}{{{base:.3f}}}\n")
        if best is not None:
            f.write(f"\\newcommand{{\\bestWithinR}}{{{best:.3f}}}\n")
            f.write(f"\\newcommand{{\\bestVariant}}{{{best_k}}}\n")
            if base:
                f.write(f"\\newcommand{{\\magGain}}{{{(best/base-1)*100:+.0f}\\%}}\n")
    print("wrote MAGNITUDE_RESULTS.md + values_magnitude.tex")
    print(f"rel_Y mean={_r(rel_mean)} | baseline={_r(base)} | best={best_k}={_r(best)}")


def _r(x):
    return round(x, 3) if isinstance(x, (int, float)) else "—"


if __name__ == "__main__":
    main()
