#!/usr/bin/env python3
"""Diagnostic: which multilevel AR(1) specification recovers a planted within-AR
of 0.30 on a SHORT (T=6) intensive-longitudinal panel?

Compares, on data generated by internal_validity_v2._simulate_corpus (planted within-AR=0.30,
ICC~0.5):
  (1) raw       : state_t ~ lag_state + (1|person)            [between-var leak -> biased UP]
  (2) within    : dev_t   ~ lag_dev   + (1|person)            [small-T within-transform -> biased DOWN]
  (3) mundlak   : state_t ~ lag_state + person_mean_of_lag + (1|person)
  (4) pooled-OLS within-centered (linregress on dev, lag_dev)

This is a saved analysis (not a one-liner) so the spec choice is reproducible.
Run: python3 scripts/validation/_ar1_spec_check.py
"""
import warnings
import numpy as np
import pandas as pd
import statsmodels.formula.api as smf

import internal_validity_v2 as g

PLANTED = 0.30
rng = np.random.default_rng(7)
gm = {"work_engagement": 4.80}
wsd = {"work_engagement": 0.74}
bsd = {"work_engagement": 0.74}  # ICC 0.5
sc = {"work_engagement": (1.0, 7.0)}
df = g._simulate_corpus(800, 6, rng, gm, bsd, wsd, sc, between_r=0.0, ar1=PLANTED)
col = "work_engagement"

sub = df.sort_values(["employee_id", "day_index"]).copy()
sub["lag"] = sub.groupby("employee_id")[col].shift(1)
sub["dev"] = sub[col] - sub.groupby("employee_id")[col].transform("mean")
sub["lag_dev"] = sub.groupby("employee_id")["dev"].shift(1)
sub["pm_lag"] = sub.groupby("employee_id")["lag"].transform("mean")
pairs = sub.dropna(subset=["lag", "lag_dev"]).copy()


def fit(formula):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        m = smf.mixedlm(formula, pairs, groups=pairs["employee_id"]).fit(reml=True, method="lbfgs")
    return m

print(f"Planted within-AR = {PLANTED};  N personas=800, T=6")
print(f"(1) raw     state~lag        : {fit(f'{col} ~ lag').fe_params['lag']:+.3f}")
print(f"(2) within  dev~lag_dev      : {fit('dev ~ lag_dev').fe_params['lag_dev']:+.3f}")
print(f"(3) mundlak state~lag+pm_lag : {fit(f'{col} ~ lag + pm_lag').fe_params['lag']:+.3f}")
from scipy import stats as sps
sl = sps.linregress(pairs['lag_dev'], pairs['dev']).slope
print(f"(4) pooled OLS dev~lag_dev   : {sl:+.3f}")

# Theory: within-group dynamic-panel (Nickell) bias ~ -(1+rho)/(T-1) for the
# within estimator at small T. For T=6 lag pairs the effective series is shorter.
print(f"\nNickell-bias guide for within est at T=6: approx -(1+rho)/(T-1) "
      f"= {-(1+PLANTED)/(6-1):+.3f} (rough)")
